"""Generate src/kgcss/_encodings.py from the WHATWG Encoding Standard data.

Download the data into an empty directory, then run this with the paths:

    mkdir /tmp/whatwg && cd /tmp/whatwg
    curl -fLO https://encoding.spec.whatwg.org/encodings.json
    curl -fLO https://encoding.spec.whatwg.org/indexes.json
    python -I tools/generate_encodings.py /tmp/whatwg/encodings.json /tmp/whatwg/indexes.json \\
        -o src/kgcss/_encodings.py
"""

import argparse
import json
from pathlib import Path

HEADER = """\
# License: GPLv3 Copyright: 2026, Kovid Goyal <kovid at kovidgoyal.net>

# Generated by tools/generate_encodings.py from the WHATWG Encoding Standard
# (https://encoding.spec.whatwg.org/). Do not edit.

from typing import Final

# Encoding label -> lowercase encoding name
LABELS: Final[dict[str, str]] = {
"""

# ISO-8859-8-I decodes exactly like ISO-8859-8
INDEX_ALIASES = {'iso-8859-8-i': 'iso-8859-8'}


def load_json(path: Path) -> object:
    with path.open(encoding='utf-8') as f:
        return json.load(f)


def generate(encodings_path: Path, indexes_path: Path) -> str:
    groups = load_json(encodings_path)
    indexes = load_json(indexes_path)
    assert isinstance(groups, list)
    assert isinstance(indexes, dict)
    labels: dict[str, str] = {}
    single_byte: list[str] = []
    for group in groups:
        for enc in group['encodings']:
            name = str(enc['name']).lower()
            for label in enc['labels']:
                assert isinstance(label, str)
                assert label.isascii()
                assert label == label.lower()
                labels[label] = name
            if group['heading'] == 'Legacy single-byte encodings':
                single_byte.append(name)
    out = [HEADER]
    out.extend(f'    {label!r}: {name!r},\n' for label, name in sorted(labels.items()))
    out.append('}\n\n')
    out.append('# Single-byte encodings: the code points for bytes 0x80 to 0xFF, with\n')
    out.append('# U+FFFE marking bytes that are errors (decoded as U+FFFD)\n')
    out.append('SINGLE_BYTE: Final[dict[str, str]] = {\n')
    for name in sorted(single_byte):
        index = indexes[INDEX_ALIASES.get(name, name)]
        assert isinstance(index, list)
        assert len(index) == 128
        table = ''.join('\ufffe' if cp is None else chr(cp) for cp in index)
        out.append(f'    {name!r}: (\n')
        for i in range(0, 128, 32):
            chunk = table[i : i + 32].encode('ascii', 'backslashreplace').decode('ascii')
            out.append(f"        '{chunk}'\n")
        out.append('    ),\n')
    out.append('}\n')
    return ''.join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('encodings', type=Path, help='Path to encodings.json')
    parser.add_argument('indexes', type=Path, help='Path to indexes.json')
    parser.add_argument('-o', '--output', type=Path, required=True, help='Where to write the generated module')
    args = parser.parse_args()
    args.output.write_text(generate(args.encodings, args.indexes), encoding='utf-8')


if __name__ == '__main__':
    main()
