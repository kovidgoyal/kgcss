"""Generate src/kgcss/_css_data.py, the data of the stylelint rules of kgcss.lint.

The data comes from the stylelint that the tests compare kgcss.lint with,
installed by `uv run --group bench python bench/bench_parse.py prepare` at the
versions pinned in bench/stylelint/package-lock.json. Needs node:

    python -I tools/generate_css_data.py -o src/kgcss/_css_data.py
    python -I tools/generate_css_data.py --check src/kgcss/_css_data.py

tools/stylelint/dump_data.mjs reads the data: what stylelint's default css-tree
lexer knows (properties, the properties that take a <dashed-ident>, function
names), and the tables of stylelint's lib/reference that the rules use,
listed in REFERENCE below. Sets become frozensets and Maps read-only
mappings of tuples, in stylelint's order (which rules report in), under
UPPER_SNAKE_CASE names. --check exits with an
error if the file differs from what would be generated.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INSTALL_DIR = ROOT / 'bench' / '.cache' / 'stylelint'
DUMP_SCRIPT = Path(__file__).resolve().parent / 'stylelint' / 'dump_data.mjs'

# The css-tree data, from the lexer: dump key -> (name, comment)
LEXER = {
    'properties': (
        'CSS_TREE_PROPERTIES',
        'The properties css-tree knows. lexer.getProperty() also finds them with any vendor prefix',
    ),
    'dashedIdentProperties': (
        'CSS_TREE_DASHED_IDENT_PROPERTIES',
        'The properties whose value can be a <dashed-ident>: custom-property-no-missing-var-function skips them',
    ),
    'functions': (
        'CSS_TREE_FUNCTIONS',
        'The functions in the syntaxes css-tree knows, lowercased: function-no-unknown accepts them',
    ),
}

# The tables of stylelint's lib/reference that the rules (and the utils they import) use
REFERENCE = (
    'aNPlusBNotationPseudoClasses',
    'aNPlusBOfSNotationPseudoClasses',
    'atKeywords',
    'atRulePagePseudoClasses',
    'basicKeywords',
    'colorProperties',
    'fontFamilyKeywords',
    'fontShorthandKeywords',
    'fontSizeKeywords',
    'htmlTypeSelectors',
    'hyphenContainingTypeSelectors',
    'lengthUnits',
    'levelOneAndTwoPseudoElements',
    'linguisticPseudoClasses',
    'longhandSubPropertiesOfShorthandProperties',
    'mathFunctions',
    'mathmlTypeSelectors',
    'mediaFeatureNames',
    'namedColorsKeywords',
    'nestingSupportedAtKeywords',
    'physicalShorthandToFlowRelativeProperties',
    'previouslyKnownPrefixedProperties',
    'previouslyKnownProperties',
    'pseudoClasses',
    'pseudoElements',
    'shadowTreePseudoElements',
    'shorthandToResetToInitialProperty',
    'svgTypeSelectors',
    'systemFontKeywords',
    'units',
    'webkitScrollbarPseudoClasses',
    'webkitScrollbarPseudoElements',
)

HEADER = """\
# License: BSD-3-Clause Copyright: 2026, Kovid Goyal <kovid at kovidgoyal.net>

# Generated by tools/generate_css_data.py. Do not edit. From:
{sources}#
# The data of the stylelint rules of kgcss.lint: what stylelint's css-tree
# lexer knows, and the tables of stylelint's lib/reference, whose names are
# the UPPER_SNAKE_CASE forms of the names here. Case is as in stylelint.

from collections.abc import Mapping
from types import MappingProxyType
from typing import Final
"""

type Table = list[str] | dict[str, list[str]]


def constant_name(name: str) -> str:
    return re.sub(r'(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])', '_', name).upper()


def string_set(items: list[str], indent: str) -> str:
    """A frozenset literal, laid out as ruff formats it."""
    if not items:
        return 'frozenset()'
    body = ''.join(f'{indent}        {item!r},\n' for item in sorted(set(items)))
    return f'frozenset(\n{indent}    {{\n{body}{indent}    }}\n{indent})'


def string_tuple(items: list[str], indent: str) -> str:
    """A tuple literal in the given order, laid out as ruff formats it."""
    if not items:
        return '()'
    body = ''.join(f'{indent}    {item!r},\n' for item in dict.fromkeys(items))
    return f'(\n{body}{indent})'


def assign(name: str, value: Table, comment: str = '') -> str:
    out = ['\n']
    if comment:
        out.append(f'# {comment}\n')
    if isinstance(value, list):
        out.append(f'{name}: Final[frozenset[str]] = {string_set(value, "")}\n')
        return ''.join(out)
    out.append(f'{name}: Final[Mapping[str, tuple[str, ...]]] = MappingProxyType(\n    {{\n')
    out.extend(f'        {key!r}: {string_tuple(value[key], "        ")},\n' for key in sorted(value))
    out.append('    }\n)\n')
    return ''.join(out)


def dump(install_dir: Path) -> dict[str, dict]:
    node = shutil.which('node')
    if node is None:
        raise SystemExit('node is not installed')
    if not (install_dir / 'node_modules' / 'stylelint').exists():
        raise SystemExit(f'stylelint is not installed in {install_dir}: run bench/bench_parse.py prepare')
    with tempfile.TemporaryDirectory() as tdir:
        output = Path(tdir) / 'data.json'
        subprocess.run([node, str(DUMP_SCRIPT), str(install_dir), str(output), *REFERENCE], check=True)
        with output.open(encoding='utf-8') as f:
            return json.load(f)


def generate(data: dict[str, dict]) -> str:
    versions = data['versions']
    sources = ''.join(f'# - {name} {version}\n' for name, version in versions.items())
    out = [HEADER.format(sources=sources)]
    for key, (name, comment) in LEXER.items():
        out.append(assign(name, data['lexer'][key], comment))
    for js_name in REFERENCE:
        out.append(assign(constant_name(js_name), data['reference'][js_name]))
    return ''.join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('-o', '--output', type=Path, help='Where to write the module')
    group.add_argument('--check', type=Path, help='Check that this module is up to date')
    parser.add_argument('--install-dir', type=Path, default=INSTALL_DIR, help='Where stylelint is installed')
    args = parser.parse_args()
    source = generate(dump(args.install_dir))
    if args.check is not None:
        if args.check.read_text(encoding='utf-8') != source:
            print(f'{args.check} is out of date: regenerate it with {Path(__file__).name}', file=sys.stderr)
            raise SystemExit(1)
        return
    args.output.write_text(source, encoding='utf-8')


if __name__ == '__main__':
    main()
